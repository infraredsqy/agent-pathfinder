#!/usr/bin/env python3
"""Write a node's signal and hand the baton on. ONE command, run by the worker session.

    python handoff.py <cycle> <node> completed -s "<summary>" -o '{...}'
    python handoff.py <cycle> <node> failed    -s "<why>"     -o '{...}'
    python handoff.py --form <cycle> [<node>]      print the ticket this line asks for; write nothing

Options:
    --dry-run / --no-spawn   accepted and ignored (this command opens no session)
    --project DIR            project root (default: cwd)

`--form` is the shape half of the same contract: it prints the `-o` skeleton with the readings THIS
line carries a line for (`asked_readings`), so a worker fills a form generated by the tool that
receives it instead of a template copied into a prompt. A line with no numeric policies prints a
skeleton with no `reading` key at all -- nothing to measure means nothing to report.

Why this exists
---------------
The worker's report and the close of its node are two separate commands on purpose:

    handoff.py <cycle> <node> <status>      write the ticket; the node stays in the cycle's hand
    next --after <node>                     close it, and the next node starts or the run stops

Keeping them apart is what lets a worker report and then think -- and it is why this program opens
no session. It also leaves a readable middle state: a ticket on disk whose node has not been closed
yet is how a chain that broke halfway shows up (the planner answers `wait` with the closing command).
The worker never reads this program's output and never touches a state file.

**交条子这一拍不驱动管线。** 写下条子之后它只读一遍下一步（`plan`，只读），把那个答案里的收尾
命令报给会话；把线推到下一个稳定动作 —— 收格、挑下一格、给下一格落 `prompt.txt` —— 全是收尾那一
拍（`next --after <node_id>`）与派发的事。所以这个命令一个字节的状态都不写，下一格的 prompt 也不
可能由报条子的会话写下。

The one gate is the cycle's own hand: a ticket is accepted only while the cycle is holding the
node, so a stale session reporting on a node that was closed and released long ago is refused
before anything is written. A node being redone is claimed again (revive, `cycle retry --drop`,
`cycle hold`), and its second ticket is legitimate: the path keeps one entry per close, so the
redo reads as the walk it was. The signal file is keyed by the node
(`.pf/signals/<cycle>/<node>.json`, next to `state.json`), so no round or stage number appears
anywhere in this command.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONDUCT = HERE.parent                      # the conduct tool directory

# `tools/shared/` is the shared layer, and it has no package to import from: every file in it is
# loaded by path through `loader.py`. These two functions are that bootstrap, identical in every file
# that needs it -- a path load, never a name import, because nothing puts `tools/` on `sys.path`.
SHARED = CONDUCT.parent / 'shared'

_LOADER = None


def _loader():
    """`tools/shared/loader.py`: the one loader, for the modules this tree keeps outside `shared/`."""
    global _LOADER
    if _LOADER is None:
        spec = importlib.util.spec_from_file_location('pf_shared_loader', SHARED / 'loader.py')
        _LOADER = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(_LOADER)
    return _LOADER


def _load(name: str, path):
    """A neighbouring file, loaded by path: how every file in this tree reaches its neighbours."""
    return _loader().load_by_path(name, path)


_STORE = None


def _store():
    """`conduct_state.store`, loaded by path -- one module per process.

    `signal.py` needs the same copy (it writes the signal through it), so it is asked for under one
    name and handed back to both. A by-name import is what this avoids: it would need `tools/` on
    `sys.path`.
    """
    global _STORE
    if _STORE is None:
        _STORE = _loader().load_by_path('pf_conduct_state_store',
                                        CONDUCT / 'conduct_state' / 'store.py',
                                        register=True, reuse=True)
    return _STORE


def _project_root(project: Path) -> Path:
    """cwd（或 `--project`）落在 linked worktree 里时回主树。

    并行模式下这一条是从 worktree 的 cwd 跑的：条子必须落主树的 `.pf/signals/`，标记落主树的
    `.pf/meta/`。判定与 `conduct_state.store._resolve_project_root` 是同一份约定，从这里借，
    不复制第四份。
    """
    return _store()._resolve_project_root(project)


def _marker():
    """`spawn/marker.py`: 断链降级标记的落点与记录形状，一处长成。

    `spawn/` 与 `pipeline/` 是同簇的两半（spawner 那一层按同一份形状自己写，那条例外写在 `marker.py`
    的说明里），加载方式与别的邻居一样走装载器。
    """
    return _loader().load_by_path('conduct_spawn_marker',
                                  CONDUCT / 'spawn' / 'marker.py',
                                  register=True, reuse=True)


def _ledger_name() -> str:
    """`.pf` 的那一个名字。跟根判定一样从 store 借，不复制第二份。"""
    return _store().LEDGER_NAME


def _write_marker(project: Path, cycle: str, phase: str, reason: str, attempts: int = 0,
                  note: str | None = None) -> None:
    # Not part of the record: the marker is a "this chain broke" flag a human deletes once they
    # have taken over, so it must not travel with the project's history. It sits in `meta/`, which
    # `.pf/.gitignore` keeps out of both the project's history and the ledger's own. One file per
    # cycle: two lines run side by side under parallel=2, and a successful spawn on line B must not
    # erase line A's "chain broke here" flag (the spawners clear the marker of their OWN cycle on
    # success).
    #
    # 落点、记录形状与那句人话以 `spawn/marker.py` 为正本（spawner 那一层按同一份形状自己写：
    # 见 `marker.py` 的说明），这里只交出这一拍知道的事：哪条线、断在哪一步、那一拍的原话。
    marker = _marker()
    path = marker.marker_path(project, cycle)
    try:
        marker.write(path, marker.record(cycle, phase, reason, attempts=attempts,
                                         workspace=project, note=note))
        print(f'WARNING: conduct handoff failed; wrote {path}', file=sys.stderr)
    except OSError as e:  # never let the marker itself become the failure
        print(f'WARNING: could not write the handoff failure marker: {e}', file=sys.stderr)


#: What one asked-for reading means, in the words a worker needs to fill it in. A key with no line
#: here still gets a slot -- its own name in angle brackets.
_READING_ASKS = {
    'test_seconds': '全量验证实测的墙钟秒数（照项目文档认定的那套命令跑，不许估算）',
}


def _print_form(project: Path, cycle_id: str, node: str | None) -> int:
    """Print the ticket this line asks for. Reads the cycle's policies; writes nothing.

    The reading slots come from the line's own policies (`asked_readings`): a line that carries no
    numeric policy asks for nothing, and a project on the `minimal` tier carries no test line, so
    its workers get a skeleton with no `reading` key at all.
    """
    pipeline = _load('conduct_pipeline', HERE / 'conduct_pipeline.py')
    cycle = pipeline.find_cycle(pipeline.load_state(project), cycle_id)
    if cycle is None:
        print(f'Error: no cycle named {cycle_id!r}.', file=sys.stderr)
        return 2
    readings = pipeline.asked_readings(cycle)
    fields = ['"deliverable":"<本节点该产出的那样东西的路径>"',
              '"acceptance":["<核心验收点1>","<核心验收点2>"]',
              '"touched":["<你这个节点改过的文件>"]']
    if readings:
        slots = ','.join(f'"{key}":<{_READING_ASKS.get(key, key)}>' for key in readings)
        fields.append(f'"reading":{{{slots}}}')
    here = Path(__file__).resolve().as_posix()
    print(f'这条线（{cycle_id}）要的条子：')
    print()
    print(f'python {here} {cycle_id} {node or "<节点id>"} completed -s "<一行总结>" '
          f"-o '{{{','.join(fields)}}}'")
    if readings:
        print()
        print('没测到的读数那个键整个删掉：缺一个数读作「这一趟不知道」，填 0 读作「已经量到零」。')
    return 0


def main(argv=None) -> int:
    # 这条命令由干活的那格在收尾时跑，输出会被会话读进上下文：统一成 UTF-8，
    # 免得控制台代码页是 GBK 时中文总结变成乱码。stderr 同样处理：报错也会被父进程读。
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, 'reconfigure'):
            stream.reconfigure(encoding='utf-8', errors='replace')
    parser = argparse.ArgumentParser(
        prog='handoff.py',
        description='Write one node\'s signal and hand the baton on (one command for a worker).')
    parser.add_argument('cycle')
    parser.add_argument('node', nargs='?', help='The DAG node this session was working on')
    parser.add_argument('status', nargs='?', choices=['completed', 'failed', 'stopped'])
    parser.add_argument('-s', '--summary', default=None)
    parser.add_argument('-o', '--outputs', default='{}', help='JSON object of key outputs')
    parser.add_argument('--form', action='store_true',
                        help='Print the ticket shape this line asks for, and stop (writes nothing)')
    parser.add_argument('--project', default='.', help='Project root (default: cwd)')
    parser.add_argument('--dry-run', '--no-spawn', dest='dry_run', action='store_true',
                        help='Accepted and ignored: this command opens no session, so "spawn '
                             'nothing" is not a mode it has (kept so an existing caller\'s argv '
                             'keeps working)')
    args = parser.parse_args(argv)

    project = _project_root(Path(args.project).resolve())
    if args.form:
        return _print_form(project, args.cycle, args.node)
    if not args.node or not args.status or args.summary is None:
        parser.error('a ticket needs <node> <status> -s "<一行总结>"; '
                     '`--form <cycle>` prints the shape')

    try:
        outputs = json.loads(args.outputs)
    except json.JSONDecodeError as e:
        print(f'Error: -o is not valid JSON: {e}', file=sys.stderr)
        return 1
    if not isinstance(outputs, dict):
        print('Error: -o must be a JSON object', file=sys.stderr)
        return 1

    signal_mod = _load('conduct_signal', HERE / 'signal.py')
    pipeline = _load('conduct_pipeline', HERE / 'conduct_pipeline.py')

    # The cycle must be holding this node. Which cycle is speaking is settled by the NODE, and this
    # is the one command where that is checked before writing: a ticket filed against a cycle that
    # is not holding the node would file evidence for work nobody is running.
    state = pipeline.load_state(project)
    cycle = pipeline.find_cycle(state, args.cycle)
    if cycle is None:
        print(f'Error: no cycle named {args.cycle!r}; nothing was written.', file=sys.stderr)
        return 2
    holding = pipeline._holding_ids(cycle)
    if args.node not in holding:
        where = (f'it is holding {", ".join(x[:8] for x in holding)}' if holding
                 else 'it is holding nothing')
        print(f'Error: cycle "{args.cycle}" is not holding {args.node} ({where}); nothing was '
              f'written.', file=sys.stderr)
        return 2
    try:
        signal_mod.write_signal(args.cycle, args.node, args.status,
                                args.summary, outputs,
                                base_dir=project / _ledger_name() / 'signals')
    except SystemExit as e:  # write_signal exits on write failure
        _write_marker(project, args.cycle, 'write-signal', f'signal write failed (exit {e.code})')
        return 1

    try:
        # 只读的一问：条子刚写下，管线此刻的答案是「等收尾」加那一条收尾命令。`record` 那半（把线
        # 推到下一个稳定动作、顺手给别的格补 prompt）留在收尾与派发那一拍，这里一个字节都不写。
        action = pipeline.plan(project, args.cycle)
    except (RuntimeError, ValueError) as e:
        _write_marker(project, args.cycle, 'plan', str(e))
        print(f'Error: the pipeline could not be read: {e}', file=sys.stderr)
        return 1

    kind = action.get('action')
    if kind == 'wait' and action.get('close_with'):
        # 这一格刚写下条子，还没被收尾。这里不 spawn 任何会话——收尾那一棒由调用方跑
        # `next --after <node_id> --json` 完成（它也不再拉会话：派发是提交推送之后的
        # 另一条命令 `dispatch <cycle>`），所以这里只报清楚别停得静悄悄。
        print(f'handoff: {args.node} ticket written; the node is not closed yet -- finish it '
              f'with `{action["close_with"]}` (no session was spawned)')
    else:
        print(f'handoff: {args.node} ticket written; the pipeline reads {kind} '
              f'({action.get("note") or action.get("reason") or ""})')
        if kind == 'fail_hard':
            # A chain that breaks leaves a loud mark and a non-zero exit. Without this the
            # worker's session sees rc=0, no session is ever started, and the run stops with
            # nobody told -- "the machine sat there quietly".
            _write_marker(
                project, args.cycle, 'bad-signal',
                action.get('reason') or 'the pipeline refused the signal',
                note=(f'这一步的条子被管线判坏（reason 里点名了原因）。清掉它重报：'
                      f'pf cycle retry {args.cycle} {args.node}，再跑一次'
                      f'handoff；确认无碍后删掉本文件。'))
            print('Error: the pipeline refused this signal; see the marker file.',
                  file=sys.stderr)
            return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
